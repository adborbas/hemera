import Foundation

/**
 Home Assistant's own icon data from `frontend/get_icons`, shaped `domain → (device_class | "_") → Entry`.

 `Codable` decodes the bundled copy only — the live payload arrives as `HAData`, which is not a
 `Decoder`, so it is decoded by hand in `IconTranslations+HAData`.
*/
struct IconTranslations: Codable, Sendable, Equatable {

    struct Entry: Codable, Sendable, Equatable {
        /// Icon used when no state-specific icon matches.
        let defaultIcon: String?
        /// Entity state → icon, e.g. `["closed": "mdi:garage"]`.
        let state: [String: String]?
        /// Per-attribute icon maps, e.g. climate's `hvac_action`.
        let stateAttributes: [String: Entry]?

        enum CodingKeys: String, CodingKey {
            case defaultIcon = "default"
            case state
            case stateAttributes = "state_attributes"
        }

        init(defaultIcon: String? = nil, state: [String: String]? = nil, stateAttributes: [String: Entry]? = nil) {
            self.defaultIcon = defaultIcon
            self.state = state
            self.stateAttributes = stateAttributes
        }
    }

    let resources: [String: [String: Entry]]

    init(resources: [String: [String: Entry]]) {
        self.resources = resources
    }

    /// Domain-wide fallback key used by Home Assistant when an entity has no matching `device_class`.
    static let domainFallbackKey = "_"

    func entry(domain: String, deviceClass: String?) -> Entry? {
        guard let domainEntries = resources[domain] else { return nil }
        if let deviceClass, let match = domainEntries[deviceClass] { return match }
        return domainEntries[Self.domainFallbackKey]
    }
}

// MARK: - Bundled Copy

extension IconTranslations {

    /**
     Generated by `scripts/update-ha-icon-translations.sh`. Demo mode's only source, and the
     first-paint seed for live sessions. Non-optional: a bad resource is a broken build.
    */
    static func bundled() -> IconTranslations {
        guard let url = Bundle.main.url(forResource: "BundledIconTranslations", withExtension: "json") else {
            preconditionFailure("BundledIconTranslations.json missing from the app bundle")
        }
        do {
            return try JSONDecoder().decode(IconTranslations.self, from: try Data(contentsOf: url))
        } catch {
            preconditionFailure("BundledIconTranslations.json could not be decoded: \(error)")
        }
    }
}
